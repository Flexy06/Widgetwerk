// Signierung: lokal aus keystore.properties, in GitHub Actions aus Env-Variablen (SIGNING_*)
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? = System.getenv(env) ?: keystoreProps.getProperty(prop)

android {
    namespace = "de.flexy.widgetwerk"
    compileSdk = 36

    defaultConfig {
        applicationId = "de.flexy.widgetwerk"
        // Android 12+: dynamische Farben, responsive Widgets, AnalogClock-Zeiger per setIcon
        minSdk = 31
        targetSdk = 36
        // CI setzt VERSION_CODE / VERSION_NAME, lokal gelten die Standardwerte
        versionCode = System.getenv("VERSION_CODE")?.toIntOrNull() ?: 1
        versionName = System.getenv("VERSION_NAME") ?: "1.0.0"
    }

    signingConfigs {
        create("release") {
            val store = signingValue("SIGNING_STORE_FILE", "storeFile")
            if (store != null) {
                storeFile = rootProject.file(store)
                storePassword = signingValue("SIGNING_STORE_PASSWORD", "storePassword")
                keyAlias = signingValue("SIGNING_KEY_ALIAS", "keyAlias")
                keyPassword = signingValue("SIGNING_KEY_PASSWORD", "keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            // Fester Release-Key (falls vorhanden), damit jede neue Version über die alte installiert werden kann
            val release = signingConfigs.getByName("release")
            signingConfig = if (release.storeFile != null) release else signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
    lint {
        // Release-Builds in CI nicht an Lint-Warnungen scheitern lassen
        checkReleaseBuilds = false
        abortOnError = false
    }
}

